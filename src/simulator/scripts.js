function event(delayMs, commentary, scores) {
  const scoreFields = Array.isArray(scores)
    ? { homeScore: scores[0], awayScore: scores[1] }
    : scores || {};

  return {
    delayMs,
    ...scoreFields,
    commentary,
  };
}

function cricketScore(homeRuns, homeWickets, awayRuns, awayWickets) {
  return {
    homeScore: homeRuns,
    homeWickets,
    awayScore: awayRuns,
    awayWickets,
  };
}

