const BUILDERS = {
  football: footballScript,
  cricket: cricketScript,
  hockey: hockeyScript,
};

export function getSimulatorScript(match) {
  const sport = String(match.sport || '').trim().toLowerCase();
  const builder = BUILDERS[sport];
  if (!builder) {
    return null;
  }

  const script = builder(match);
  const estimatedDurationMs = script.events.reduce((sum, item) => sum + item.delayMs, 0);
  return { ...script, estimatedDurationMs };
}

export const SIMULATOR_SPORTS = Object.keys(BUILDERS);
